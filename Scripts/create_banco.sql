CREATE TABLE TB_TUTOR (
    ID_TUTOR DECIMAL(18,0) NOT NULL,
    NOME_TUTOR VARCHAR(100) NOT NULL,
    CPF_TUTOR VARCHAR(14) NOT NULL,
    TELEFONE_TUTOR VARCHAR(20) NOT NULL,
    EMAIL_TUTOR VARCHAR(150) NOT NULL,
    CEP_TUTOR VARCHAR(10) NOT NULL,
    RUA_TUTOR VARCHAR(150) NOT NULL,
    NUMERO_TUTOR VARCHAR(20) NOT NULL,
    COMPLEMENTO_TUTOR VARCHAR(100) NULL,
    BAIRRO_TUTOR VARCHAR(100) NOT NULL,
    CIDADE_TUTOR VARCHAR(100) NOT NULL,
    ESTADO_TUTOR VARCHAR(100) NOT NULL,
    DATA_CADASTRO_TUTOR DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_TB_TUTOR PRIMARY KEY (ID_TUTOR)
);

CREATE TABLE TB_VETERINARIO (
    ID_VETERINARIO DECIMAL(18,0) NOT NULL,
    NOME_VETERINARIO VARCHAR(MAX) NOT NULL,
    CRM_VETERINARIO VARCHAR(MAX) NOT NULL,
    ESPECIALIDADE_VETERINARIO VARCHAR(MAX) NOT NULL,
    TELEFONE_VETERINARIO VARCHAR(MAX) NULL,
    EMAIL_VETERINARIO VARCHAR(MAX) NULL,
    STATUS_VETERINARIO VARCHAR(MAX) NULL,
    DATA_CADASTRO_VETERINARIO DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_TB_VETERINARIO PRIMARY KEY (ID_VETERINARIO)
);

CREATE TABLE TB_PET (
    ID_PET DECIMAL(18,0) NOT NULL,
    ID_TUTOR DECIMAL(18,0) NOT NULL,
    NOME_PET VARCHAR(100) NOT NULL,
    ESPECIE_PET VARCHAR(50) NOT NULL,
    RACA_PET VARCHAR(80) NOT NULL,
    SEXO_PET VARCHAR(10) NOT NULL,
    DATA_NASCIMENTO_PET DATETIME2 NOT NULL,
    PESO_PET DECIMAL(18,2) NOT NULL,
    COR_PET VARCHAR(50) NOT NULL,
    DATA_CADASTRO_PET DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_TB_PET PRIMARY KEY (ID_PET),
    CONSTRAINT FK_TB_PET_TB_TUTOR FOREIGN KEY (ID_TUTOR) REFERENCES TB_TUTOR(ID_TUTOR)
);